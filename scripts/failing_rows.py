"""Render main-eval rows where the unedited MiniLM fails. Reads runs/base/, writes docs/m5_failing_rows.md.

Picks one row per failure target with a fixed seed, so the rows cover both NRIC contexts, the name-word
confusions, boundary errors, misses and false positives, then fills up with the rows that hold the most failures.
"""

import json
import random

from wsp.data import ROOT, SETS, Doc, Span, read_jsonl
from wsp.outcomes import Outcome, outcomes
from wsp.score import SG_LABELS, scored_label, split_names

SEED = 20261105
ROWS = 12
MAX_CHARS = 700
TARGETS = (
    ("NRIC with tax context, wrong", lambda o: o.kind == "national_id/tax context" and not o.correct),
    ("NRIC without tax context, wrong", lambda o: o.kind == "national_id/no tax context" and not o.correct),
    ("Later word of a given name typed as surname",
     lambda o: o.kind == "first_name/multi-word, later word" and o.got == "last_name"),
    ("One-word given name typed as surname", lambda o: o.kind == "first_name/one word" and o.got == "last_name"),
    ("Given name missed", lambda o: o.word.label == "first_name" and o.got == "missed"),
    ("Surname missed", lambda o: o.word.label == "last_name" and o.got == "missed"),
    ("Name boundary error", lambda o: o.got.startswith("boundary") and o.word.label != "national_id"),
    ("False positive", None),
)


def false_positives(d: Doc, pred: list[Span]) -> list[Span]:
    """Scored predictions that overlap no scored gold entity and no ignore span, as `wsp.score.grade` counts them."""
    gold = [w for g in d.spans if g.label in SG_LABELS for w in split_names(d.text, [g])]
    words = [Span(p.start, p.end, scored_label(d.text, p, SG_LABELS)) for p in split_names(d.text, pred)]
    return [p for p in words if p.label in SG_LABELS
            and not any(p.start < g.end and g.start < p.end for g in gold)
            and not any(p.start < i.end and i.start < p.end for i in d.ignore)]


def render(i: int, why: str, d: Doc, outs: list[Outcome], fps: list[Span]) -> list[str]:
    lines = [f"### {i}. {why}, `{d.id}`", "", f"> {d.text.replace(chr(10), ' ⏎ ')}", "",
             "| Gold span | Kind | Scored entity | MiniLM output | Correct |", "|---|---|---|---|---|"]
    lines += [f"| `{d.value(o.gold)}` | {o.kind} | `{d.value(o.word)}` | {o.got} | {'yes' if o.correct else 'no'} |"
              for o in outs]
    if fps:
        lines += ["", "False positives: " + ", ".join(f"`{d.value(p)}` as {p.label}" for p in fps)]
    return lines + [""]


def main() -> None:
    docs = {d.id: d for d in read_jsonl(SETS / "sg_eval.jsonl")}
    with (ROOT / "runs" / "base" / "pred_sg_eval.jsonl").open() as f:
        preds = {r["id"]: [Span(**s) for s in r["spans"]] for r in map(json.loads, f)}
    pool = []
    for doc_id, d in docs.items():
        outs, fps = outcomes(d, preds[doc_id]), false_positives(d, preds[doc_id])
        if len(d.text) <= MAX_CHARS and (fps or not all(o.correct for o in outs)):
            pool.append((d, outs, fps))
    random.Random(SEED).shuffle(pool)

    picked, used = [], set()
    for why, hit in TARGETS:
        row = next(r for r in pool if r[0].id not in used
                   and (bool(r[2]) if hit is None else any(hit(o) for o in r[1])))
        picked.append((why, *row))
        used.add(row[0].id)
    by_failures = sorted((r for r in pool if r[0].id not in used),
                         key=lambda r: -(sum(not o.correct for o in r[1]) + len(r[2])))
    picked += [("Many failures", *r) for r in by_failures[:ROWS - len(picked)]]

    body = [line for i, row in enumerate(picked, 1) for line in render(i, *row)]
    wrong = sum(not o.correct for _, _, outs, _ in picked for o in outs)
    total = sum(len(outs) for _, _, outs, _ in picked)
    head = ["# M5 failing rows", "",
            f"Generated by `scripts/failing_rows.py` with seed {SEED} from the M5 baseline predictions. All {ROWS} rows "
            "come from the main eval, which Opus 5.5 never sees. Rows 1 to 8 each show one failure target. Rows 9 to "
            f"{ROWS} are the rows with the most failures among the rest.", "",
            "Each table lists the scored entities. Scoring splits each `first_name` and `last_name` span into one entity "
            "per word. The MiniLM output is the scored label on the entity's exact span, `boundary: <label>` when a "
            "prediction only overlaps it, or `missed`. A `tax_id` output on an NRIC is already scored as `national_id`. "
            "An NRIC has tax context when \"tax\" appears in the 60 characters before it. ⏎ marks a line break.", "",
            f"MiniLM gets {total - wrong} of {total} scored entities right on these rows.", "", "## Rows", ""]
    out = ROOT / "docs" / "m5_failing_rows.md"
    out.write_text("\n".join(head + body))
    print(f"wrote {out.relative_to(ROOT)}: {len(picked)} rows, {total - wrong}/{total} correct")


if __name__ == "__main__":
    main()
