"""Render main-eval rows where the unedited MiniLM fails. Reads runs/base/, writes docs/m5_failing_rows.md.

Picks one row per failure target with a fixed seed, so the rows cover both NRIC contexts, the name-word
confusions, boundary errors, misses and false positives, then fills up with the rows that hold the most failures.
"""

import json
import random

from wsp.data import ROOT, SETS, Doc, Span, read_jsonl
from wsp.outcomes import Outcome, outcomes
from wsp.score import SG_LABELS, merged, scored_label, split_names

SEED = 20261105
ROWS = 12
MAX_CHARS = 700
CATEGORY = {
    "national_id/tax context": 'NRIC with "tax" just before it',
    "national_id/no tax context": 'NRIC without "tax" just before it',
    "first_name/one word": "Given name of one word",
    "first_name/multi-word, first word": "Given name of several words, first word",
    "first_name/multi-word, later word": "Given name of several words, later words",
    "last_name/one word": "Surname of one word",
    "last_name/multi-word, first word": "Surname of several words, first word",
    "last_name/multi-word, later word": "Surname of several words, later words",
}
TARGETS = (
    ('NRIC with "tax" just before it, wrong', lambda o: o.kind == "national_id/tax context" and not o.correct),
    ('NRIC without "tax" just before it, wrong', lambda o: o.kind == "national_id/no tax context" and not o.correct),
    ("Name missed", lambda o: o.want == "name" and o.got == "missed"),
    ("Name tagged as part of a company name", lambda o: o.want == "name" and o.got == "boundary: company_name"),
    ("Name tagged with the wrong start or end", lambda o: o.want == "name" and o.got == "boundary: name"),
    ("Name tagged as another type",
     lambda o: o.want == "name" and o.got not in ("name", "missed") and not o.got.startswith("boundary")),
    ("False positive", None),
)


def false_positives(d: Doc, pred: list[Span]) -> list[Span]:
    """Scored predictions that overlap no scored gold entity and no ignore span, as `wsp.score.grade` counts them."""
    gold = [w for g in d.spans if merged(g.label, SG_LABELS) in SG_LABELS for w in split_names(d.text, [g])]
    words = [Span(p.start, p.end, scored_label(d.text, p, SG_LABELS)) for p in split_names(d.text, pred)]
    return [p for p in words if p.label in SG_LABELS
            and not any(p.start < g.end and g.start < p.end for g in gold)
            and not any(p.start < i.end and i.start < p.end for i in d.ignore)]


def render(i: int, why: str, d: Doc, outs: list[Outcome], fps: list[Span]) -> list[str]:
    lines = [f"### {i}. {why}, `{d.id}`", "", f"> {d.text.replace(chr(10), ' ⏎ ')}", "",
             "| Gold span | Category | What is scored | MiniLM output | Correct |", "|---|---|---|---|---|"]
    lines += [f"| `{d.value(o.gold)}` | {CATEGORY[o.kind]} | `{d.value(o.word)}` | {o.got} | "
              f"{'yes' if o.correct else 'no'} |" for o in outs]
    if fps:
        lines += ["", "False positives: " + ", ".join(f"`{d.value(p)}` as {p.label}" for p in fps)]
    return lines + [""]


def main() -> None:
    docs = {d.id: d for d in read_jsonl(SETS / "sg_eval.jsonl")}
    with (ROOT / "runs" / "base" / "pred_sg_eval.jsonl").open() as f:
        preds = {r["id"]: [Span(**s) for s in r["spans"]] for r in map(json.loads, f)}
    pool = []
    for doc_id, d in docs.items():
        outs, fps = outcomes(d, preds[doc_id]), false_positives(d, preds[doc_id])
        if len(d.text) <= MAX_CHARS and (fps or not all(o.correct for o in outs)):
            pool.append((d, outs, fps))
    fp_total = sum(len(false_positives(d, preds[i])) for i, d in docs.items())
    graded = json.loads((ROOT / "runs" / "base" / "baseline.json").read_text())["scores"]["singapore"]["failures"]
    if fp_total != graded["false_positive"]:
        raise RuntimeError(f"false_positives finds {fp_total}, the scoring code {graded['false_positive']}")
    random.Random(SEED).shuffle(pool)

    picked, used = [], set()
    for why, hit in TARGETS:
        row = next(r for r in pool if r[0].id not in used
                   and (bool(r[2]) if hit is None else any(hit(o) for o in r[1])))
        picked.append((why, *row))
        used.add(row[0].id)
    by_failures = sorted((r for r in pool if r[0].id not in used),
                         key=lambda r: -(sum(not o.correct for o in r[1]) + len(r[2])))
    picked += [("Many failures", *r) for r in by_failures[:ROWS - len(picked)]]

    body = [line for i, row in enumerate(picked, 1) for line in render(i, *row)]
    wrong = sum(not o.correct for _, _, outs, _ in picked for o in outs)
    total = sum(len(outs) for _, _, outs, _ in picked)
    head = ["# M5 failing rows", "",
            f"Generated by `scripts/failing_rows.py` with seed {SEED} from the M5 baseline predictions. All {ROWS} rows "
            f"come from the main eval, which Opus 5.5 never sees. In rows 1 to {len(TARGETS)}, the title names the failure "
            f"each row shows. Rows {len(TARGETS) + 1} to {ROWS} are the rows with the most failures among the rest.", "",
            "Each table has one line for each name word or NRIC that is scored. A gold span is a correct answer marked "
            "in the data. Scoring counts each word of a `first_name` or `last_name` span separately, and scores both "
            "labels as one, `name`, so either output is right on any name word. The MiniLM output "
            "is the scored label on that word or NRIC's exact span, `boundary: <label>` when a prediction only overlaps "
            "it, or `missed`. A `tax_id` output on an NRIC is already scored as `national_id`. An NRIC has \"tax\" just "
            "before it when \"tax\" appears within the 60 characters before the number, about ten words. ⏎ marks a line "
            "break.", "",
            f"On these rows, MiniLM gets {total - wrong} of the {total} scored name words and NRICs right.", "",
            "## Rows", ""]
    out = ROOT / "docs" / "m5_failing_rows.md"
    out.write_text("\n".join(head + body))
    print(f"wrote {out.relative_to(ROOT)}: {len(picked)} rows, {total - wrong}/{total} correct")


if __name__ == "__main__":
    main()
