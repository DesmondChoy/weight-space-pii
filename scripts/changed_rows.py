"""Render a random sample of the rows Opus 5.5's edit changed. Reads runs/p50/eval/, writes docs/m7_changed_rows.md.

Draws the same number of fixed and broken rows from each set with a fixed seed, so the sample is not chosen by
hand. Each row shows every tag that differs between the unedited and the edited MiniLM, next to the gold label.
"""

import json
import random

from wsp.data import ROOT, SETS, Doc, Span, read_jsonl

SEED = 20261106
PER_STATUS = 5
CONTEXT = 160
SETS_SHOWN = {"sg_eval": "Singapore main eval", "nemotron_eval": "Nemotron regression check"}
STATUS = {"fixed": "fewer errors after the edit", "broken": "more errors after the edit"}


def gold_at(d: Doc, s: Span) -> str:
    if exact := [g.label for g in d.spans if (g.start, g.end) == (s.start, s.end)]:
        return exact[0]
    if over := [g.label for g in d.spans if g.start < s.end and s.start < g.end]:
        return f"overlaps {over[0]}"
    return "none"


def excerpt(d: Doc, spans: list[Span]) -> str:
    start = max(0, min(s.start for s in spans) - CONTEXT)
    end = min(len(d.text), max(s.end for s in spans) + CONTEXT)
    body = d.text[start:end].replace("\n", " ⏎ ")
    return ("…" if start else "") + body + ("…" if end < len(d.text) else "")


def render(i: int, row: dict, d: Doc) -> list[str]:
    base = {(s[0], s[1]): s[2] for s in row["base_only_spans"]}
    edited = {(s[0], s[1]): s[2] for s in row["edited_only_spans"]}
    spans = [Span(a, b, "") for a, b in sorted(base.keys() | edited.keys())]
    b, e = row["base"], row["edited"]
    lines = [f"### {i}. {row['status'].capitalize()}, `{d.id}`", "",
             f"Errors {b['fp'] + b['fn']} → {e['fp'] + e['fn']}: false positives {b['fp']} → {e['fp']}, "
             f"missed or wrong {b['fn']} → {e['fn']}.", "", f"> {excerpt(d, spans)}", "",
             "| Text | Gold label | Unedited MiniLM | Edited MiniLM |", "|---|---|---|---|"]
    lines += [f"| `{d.value(s)}` | {gold_at(d, s)} | {base.get((s.start, s.end), 'nothing')} | "
              f"{edited.get((s.start, s.end), 'nothing')} |" for s in spans]
    return lines + [""]


def main() -> None:
    rows = [json.loads(line) for line in (ROOT / "runs" / "p50" / "eval" / "changed_rows.jsonl").open()]
    rng = random.Random(SEED)
    body, n = [], 0
    for set_name, title in SETS_SHOWN.items():
        docs = read_jsonl(SETS / f"{set_name}.jsonl")
        body += [f"## {title}", ""]
        for status in STATUS:
            pool = [r for r in rows if r["set"] == set_name and r["status"] == status]
            for r in sorted(rng.sample(pool, PER_STATUS), key=lambda r: r["position"]):
                d = docs[r["position"]]
                assert d.id == r["id"], f"{set_name} row {r['position']} is {d.id}, not {r['id']}"
                n += 1
                body += render(n, r, d)
    head = ["# M7 changed rows", "",
            f"Generated by `scripts/changed_rows.py` with seed {SEED} from `runs/p50/eval/changed_rows.jsonl`. For each "
            f"hidden set, {PER_STATUS} rows are drawn at random from the rows with fewer errors after the edit, fixed, "
            f"and {PER_STATUS} from the rows with more, broken. Opus 5.5 never saw either set.", "",
            "An error is a false positive, or a gold entity that is missed or wrong. Each table lists every tag that "
            "differs between the two models, with the gold label on the same text. `nothing` means that model put no "
            "tag on exactly that text. On Singapore text `first_name` and `last_name` both count as `name`, and "
            "`tax_id` on an NRIC counts as `national_id`. On Nemotron every label is scored as it is. The quote shows "
            f"the text from {CONTEXT} characters before the first changed tag to {CONTEXT} after the last. ⏎ marks a "
            "line break.", ""]
    out = ROOT / "docs" / "m7_changed_rows.md"
    out.write_text("\n".join(head + body))
    print(f"wrote {out.relative_to(ROOT)}: {n} rows")


if __name__ == "__main__":
    main()
