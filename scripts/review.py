"""Render the M3 review rows: gold spans, scored entities, the expected base label, and the base output.

Picks 6 practice rows and 6 main-eval rows with a fixed seed, so that each half covers every kind of
scored entity: one-word and multi-word given names, one-word and multi-word surnames, and NRICs.
The expected label for an entity is the most common base-model outcome for entities of the same
kind across the practice rows not under review. Writes docs/m3_review.md.
"""

import random
from collections import Counter, defaultdict

from wsp.data import ROOT, SETS, Doc, Span, read_jsonl
from wsp.predict import load, predict
from wsp.score import NAME_LABELS, SG_LABELS, scored_label, split_names

SEED = 20261104
PER_SET = 6
MAX_CHARS = 700
KINDS = ("first_name/one word", "first_name/multi-word", "last_name/one word", "last_name/multi-word", "national_id")
CATEGORY = {
    "first_name/one word": "Given name of one word",
    "first_name/multi-word, first word": "Given name of several words, first word",
    "first_name/multi-word, later word": "Given name of several words, later words",
    "last_name/one word": "Surname of one word",
    "last_name/multi-word, first word": "Surname of several words, first word",
    "last_name/multi-word, later word": "Surname of several words, later words",
    "national_id": "NRIC",
}


def kind(d: Doc, gold: Span) -> str:
    if gold.label not in NAME_LABELS:
        return gold.label
    return f"{gold.label}/{'multi-word' if len(d.value(gold).split()) > 1 else 'one word'}"


def position(d: Doc, gold: Span, word: Span) -> str:
    if gold.label not in NAME_LABELS or len(d.value(gold).split()) == 1:
        return kind(d, gold)
    return f"{kind(d, gold)}, {'first word' if word.start == gold.start else 'later word'}"


def outcomes(d: Doc, pred: list[Span]) -> list[tuple[Span, Span, str]]:
    """(gold span, scored entity, base outcome) for each scored entity in the document."""
    pred_words = split_names(d.text, pred)
    exact = {(p.start, p.end): p.label for p in pred_words}
    out = []
    for g in d.spans:
        for w in split_names(d.text, [g]):
            if (w.start, w.end) in exact:
                got = exact[(w.start, w.end)]
            else:
                over = [p for p in pred_words if p.start < w.end and w.start < p.end]
                got = f"boundary: {over[0].label} on `{d.value(over[0])}`" if over else "missed"
            out.append((g, w, got))
    return out


def correct(d: Doc, word: Span, got: str) -> bool:
    return scored_label(d.text, Span(word.start, word.end, got), SG_LABELS) == word.label


def pick(docs: list[Doc], rng: random.Random) -> list[Doc]:
    pool = [d for d in docs if len(d.text) <= MAX_CHARS and d.spans]
    rng.shuffle(pool)
    chosen: list[Doc] = []
    for k in KINDS:
        if not any(kind(d, g) == k for d in chosen for g in d.spans):
            chosen.append(next(d for d in pool if d not in chosen and any(kind(d, g) == k for g in d.spans)))
    rich = [d for d in pool if d not in chosen and len({kind(d, g) for g in d.spans}) >= 3]
    return chosen + rich[:PER_SET - len(chosen)]


def render(name: str, d: Doc, rows: list[tuple[Span, Span, str]], expected: dict) -> list[str]:
    text = d.text.replace("\n", " ⏎ ")
    lines = [f"### {name} `{d.id}`", "", f"> {text}", "",
             "| Gold span | Gold label | What is scored | Expected base output | Base output | Correct |",
             "|---|---|---|---|---|---|"]
    for g, w, got in rows:
        exp = expected.get(position(d, g, w), "no prior")
        lines.append(f"| `{d.value(g)}` | `{g.label}` | `{d.value(w)}` | {exp} | {got} | "
                     f"{'yes' if correct(d, w, got) else 'no'} |")
    return lines + [""]


def main() -> None:
    tok, model = load()
    rng = random.Random(SEED)
    practice = read_jsonl(SETS / "sg_train.jsonl")
    main_eval = read_jsonl(SETS / "sg_eval.jsonl")
    picked = [("Practice", d) for d in pick(practice, rng)] + [("Main eval", d) for d in pick(main_eval, rng)]
    review_ids = {d.id for _, d in picked}

    prior = defaultdict(Counter)
    prior_docs = [d for d in practice if d.id not in review_ids]
    for d, pred in zip(prior_docs, predict(tok, model, [d.text for d in prior_docs])):
        for g, w, got in outcomes(d, pred):
            prior[position(d, g, w)][got if not got.startswith("boundary") else "wrong boundary"] += 1
    expected = {k: c.most_common(1)[0][0] for k, c in prior.items()}

    preds = predict(tok, model, [d.text for _, d in picked])
    body, hits, total = [], 0, 0
    for i, ((name, d), pred) in enumerate(zip(picked, preds), 1):
        rows = outcomes(d, pred)
        hits += sum(correct(d, w, got) for _, w, got in rows)
        total += len(rows)
        body += render(f"{i}. {name}", d, rows, expected)

    head = ["# M3 review rows", "",
            f"Generated by `scripts/review.py` with seed {SEED}. Rows 1 to {PER_SET} are practice rows, which Opus 5.5 sees.",
            f"Rows {PER_SET + 1} to {2 * PER_SET} are main-eval rows, which Opus 5.5 never sees.", "",
            "Each table lists the gold spans for the scored labels as openpii marks them. A gold span is a correct "
            "answer marked in the data. Each table has one line for each name word or NRIC that is scored, because "
            "scoring counts each word of a `first_name` or `last_name` span separately. The expected base output is "
            "the most common output of the unedited MiniLM for the same category on the other "
            f"{len(prior_docs)} practice rows. The base output is what the unedited MiniLM produced on this row. "
            "A `tax_id` output on an NRIC counts as correct. ⏎ marks a line break in the text.", "",
            f"On these rows, the unedited MiniLM gets {hits} of the {total} scored name words and NRICs exactly right.",
            "", "## Expected base output by category", "",
            "| Category | Count on practice rows | Most common outcome | Share |", "|---|---|---|---|"]
    for k in sorted(prior):
        c = prior[k]
        top, n = c.most_common(1)[0]
        head.append(f"| {CATEGORY[k]} | {sum(c.values())} | {top} | {n / sum(c.values()):.0%} |")
    out = ROOT / "docs" / "m3_review.md"
    out.write_text("\n".join(head + ["", "## Rows", ""] + body))
    print(f"wrote {out.relative_to(ROOT)}: {len(picked)} rows, {hits}/{total} correct")


if __name__ == "__main__":
    main()
